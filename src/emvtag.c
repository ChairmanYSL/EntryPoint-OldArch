int32_t GetTagLength(uint32_t tag)
{
    int32_t length = 0;

    while (tag > 0)
	{
        tag >>= 8;
        length++;
    }

    return length;
}

uint8_t *GetTagName(uint32_t ui_tag)
{
	int32_t length = GetTagLength(ui_tag);
	uint8_t *uc_tag;
	int32_t i;

	uc_tag = (uint8_t *)malloc(length);
	emv_memset(uc_tag, 0, length);

	for(i = 0; i < length; i++)
	{
		uc_tag[i] = (uint8_t)((ui_tag >> (8 * (length - i - 1))) & 0xFF);
	}

	return uc_tag;
}

