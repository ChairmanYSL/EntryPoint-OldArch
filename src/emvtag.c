static int32_t binarysearch(const int32_t *arr, int32_t l, int32_t r, int32_t x)
{
	int32_t mid = l + (r - l) / 2;

	while (arr[mid] != x)
	{
		if (r <= l || r < 0)
		{
			 return -1;
		}

		if (arr[mid] > x)
       {
			 r = mid - 1;
		}
		else
		{
			 l = mid + 1;
		}

		mid = l + (r - l) / 2;
	}

    return mid;
}


uint8_t emv_taglib_read_UpdateCondition(uint32_t tag, uint32_t belong, uint8_t matchMode, uint8_t Update, EMV_TAG_ITEM *item)
{
	uint16_t size,left,right,mid;
	uint8_t readRes = 0;
	int32_t pos;

	if(tag <= 0)
	{
		return readRes;
	}

	size = sizeof(g_emv_tag_lib)/sizeof(g_emv_tag_lib[0]);
//	eTRACE("database-info: size = %d", size);

	left = 0;
	right = size - 1;
	readRes = 1;
	pos = -1;

//	eTRACE("database-info: mid start = %d", mid);

	//binary search
	while (left <= right)
	{
		mid = left + (right - left) / 2;

//		eTRACE("database-info: g_emv_tag_lib[mid].Tag = %03X", g_emv_tag_lib[mid].Tag);
//		eTRACE("database-info: tag = %03X", tag);
		if(g_emv_tag_lib[mid].Tag == tag)
		{
			if(1 == matchMode)	//match brand belong and update condition
			{
				if((g_emv_tag_lib[mid].belong & belong) && (g_emv_tag_lib[mid].Update & Update))
				{
					readRes = 0;
					pos = mid;
					break;
				}
				else
				{
					//found tag but not match belong and update,continue forward and backforward search six position
					int32_t foundPos = -1;
					int32_t i;
					for(i = 1; i <= 6; i++)
					{
						if((int32_t)mid - i < 0)
						{
							break;
						}

						if(g_emv_tag_lib[mid - i].Tag != tag)
						{
							break;
						}

						if((g_emv_tag_lib[mid - i].belong & belong) && (g_emv_tag_lib[mid - i].Update & Update))
						{
							foundPos = mid - i;
							break;
						}
					}

					if (foundPos == -1)
					{
						for (i = 1; i <= 6; i++)
						{
							// 如果越界了就退出
							if (mid + i >= size)
							{
								break;
							}

							if (g_emv_tag_lib[mid + i].Tag != tag)
							{
								break;
							}

							if ((g_emv_tag_lib[mid + i].belong & belong) && (g_emv_tag_lib[mid + i].Update & Update))
							{
								foundPos = mid + i;
								break;
							}
						}
					}

					if (foundPos >= 0)
					{
						readRes = 0;
						pos = foundPos;
					}

					break;
				}
			}
			else
			{
				readRes = 0;
				//not match belong and update condition,find left most same tag
                while (mid > 0 && g_emv_tag_lib[mid - 1].Tag == tag)
                {
                    mid--;
                }
                pos = mid;
                break;
			}
		}
		else if(g_emv_tag_lib[mid].Tag > tag)
		{
            if (mid == 0)	//Boundary restrictions
            {
                break;
            }
			right = mid - 1;
		}
		else
		{
			left = mid + 1;
		}

		mid = left + (right - left) / 2;

//		eTRACE("database-info: mid = %d", mid);
//		eTRACE("database-info: right = %d", right);
//		eTRACE("database-info: left = %d", left);
	}

	if(item != NULL)
	{
        emv_memset(item, 0, sizeof(EMV_TAG_ITEM));
        if (readRes == 0 && pos >= 0)
        {
            item->Tag     = g_emv_tag_lib[pos].Tag;
            item->Update  = g_emv_tag_lib[pos].Update;
            item->minLen  = g_emv_tag_lib[pos].minLen;
            item->maxLen  = g_emv_tag_lib[pos].maxLen;
            item->Format  = g_emv_tag_lib[pos].Format;
            item->belong  = g_emv_tag_lib[pos].belong;
        }
		else
		{
            item->Tag     = g_emv_tag_lib[pos].Tag;
		}
	}

	return readRes;
}

int32_t emv_taglib_ReadItemWithExactMatch(uint32_t tag, uint32_t belong, EMV_TAG_ITEM *item)
{
    uint16_t size, left, right, mid;
    int32_t pos = -1;
    int32_t i;

    if(item == NULL)
    {
        return EMV_ERR;
    }

    size = sizeof(g_emv_tag_lib)/sizeof(g_emv_tag_lib[0]);
    left = 0;
    right = size - 1;
    emv_memset((void *)item, 0, sizeof(EMV_TAG_ITEM));

	//binary search tagname
    while (left <= right)
    {
        mid = left + (right - left) / 2;

        if(g_emv_tag_lib[mid].Tag == tag)
        {
            pos = mid;
            break;
        }
        else if(g_emv_tag_lib[mid].Tag > tag)
        {
            if (mid == 0)
            {
                break;
            }
            right = mid - 1;
        }
        else
        {
            left = mid + 1;
        }
    }

    if(pos < 0)
    {
        return EMV_ERR;
    }

	//left forward check belong
    for(i = pos; i >= 0 && i >= pos - 10; i--)
    {
        if(g_emv_tag_lib[i].Tag != tag)
        {
            break;
        }

        if(g_emv_tag_lib[i].belong & belong)
        {
            pos = i;
            goto FOUND;
        }
    }

    // right forward check belong
    for(i = pos + 1; i < size && i <= pos + 10; i++)
    {
        if(g_emv_tag_lib[i].Tag != tag)
        {
            break;
        }

        if(g_emv_tag_lib[i].belong & belong)
        {
            pos = i;
            goto FOUND;
        }
    }

    // 如果都没找到
    return EMV_ERR;

FOUND:
    item->Tag    = g_emv_tag_lib[pos].Tag;
    item->Update = g_emv_tag_lib[pos].Update;
    item->minLen = g_emv_tag_lib[pos].minLen;
    item->maxLen = g_emv_tag_lib[pos].maxLen;
    item->Format = g_emv_tag_lib[pos].Format;
    item->belong = g_emv_tag_lib[pos].belong;

    return EMV_OK;
}

uint8_t emv_ParseExtLenWithMaxLen(uint8_t *ParseData,uint16_t *index,uint16_t *DataLen,uint16_t MaxLen)
{
	uint8_t t;
	uint16_t j,k,templen;

	k = *index;
	if(ParseData[k]<=127)
	{
		templen=ParseData[k];
		k++;
	}
	else
	{
		templen=0;
		t=ParseData[k]&0x7F;
		if(t>2)
		{
			return 1;
		}
		for(j=1; j<=t; j++)
		{
			if((k+j) > MaxLen)
		    {
		    	return 1;
		    }
			templen=templen*256+ParseData[k+j];
		}
		k += t+1;
	}
	*index = k;
	*DataLen = templen;
	return 0;
}

