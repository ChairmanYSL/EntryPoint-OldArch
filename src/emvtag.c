int32_t OutputTLV(EMV_TLVOBJ *tlvs, int32_t tlv_size, uint8_t *output, int32_t output_size)
{
	int32_t i=0,pos,tag_len,j;
	uint8_t tag[3]={0};

	if(tlvs == NULL || tlv_size < 0 || output == NULL || output_size < 0)
	{
		return EMV_FAIL;
	}

	eTRACE("paypass-info: tlvs[1].childnum = %d", tlvs[1].childnum);

	for(pos = 2; pos < tlvs[1].childnum+2; pos++)
	{
		tag_len = GetTagLength(tlvs[pos].tagname);

		emv_memset(tag, 0, sizeof(tag));

		emv_dec2hex(tlvs[pos].tagname, tag, tag_len);

		eTRACE_HEX("paypass-info: OutputTLV tag", tag, tag_len);

		emv_memcpy(output+i, tag, tag_len);
		i += tag_len;
		output[i++] = tlvs[pos].valuelen;
		emv_memcpy(output+i, tlvs[pos].pvalue, tlvs[pos].valuelen);
		i += tlvs[pos].valuelen;
	}

	return i;
}

bool IsTagIncludeTemplateValid(uint32_t tag, uint32_t tmplate, uint8_t RFU)
{
	int32_t i,size,left,right,mid;

	eTRACE("paypass-info: input tmplate = %02X", tmplate);

	if(TAG_00A5_FCI_PROPRIETARY_TEMPLATE == tmplate)
	{
		for(i = 0; i < sizeof(g_templateA5_list)/sizeof(uint32_t); i++)
		{
			if(tag == g_templateA5_list[i])
			{
				return true;
			}
		}
	}
	else if(TAG_BF0C_FCI_ISSUER_DISCRETIONARY_DATA == tmplate)
	{
		for(i = 0; i < sizeof(g_templateBF0C_list)/sizeof(uint32_t); i++)
		{
			if(tag == g_templateBF0C_list[i])
			{
				return true;
			}
		}
	}
	else if(TAG_006F_FCI_TEMPLATE == tmplate)
	{
		for(i = 0; i < sizeof(g_template6F_list)/sizeof(uint32_t); i++)
		{
			if(tag == g_template6F_list[i])
			{
				return true;
			}
		}
	}
	else if(TAG_0070_AEF_DATA_TEMPLATE == tmplate)
	{
		size = sizeof(g_template70_list)/sizeof(uint32_t);

		left = 0;
		right = size - 1;

		//binary search
		while (left <= right)
		{
			mid = left + (right - left) / 2;

			if(g_template70_list[mid] == tag)
			{
				return true;
			}
			else if(g_template70_list[mid] > tag)
			{
				if (mid == 0)	//Boundary restrictions
				{
					break;
				}
				right = mid - 1;
			}
			else
			{
				left = mid + 1;
			}

			mid = left + (right - left) / 2;
		}
	}
	else if(TAG_0077_RESPONSE_MESSAGE_TEMPLATE_FORMAT_2 == tmplate)
	{
		size = sizeof(g_template77_list)/sizeof(uint32_t);

		left = 0;
		right = size - 1;

		//binary search
		while (left <= right)
		{
			mid = left + (right - left) / 2;

			if(g_template77_list[mid] == tag)
			{
				return true;
			}
			else if(g_template77_list[mid] > tag)
			{
				if (mid == 0)	//Boundary restrictions
				{
					break;
				}
				right = mid - 1;
			}
			else
			{
				left = mid + 1;
			}

			mid = left + (right - left) / 2;
		}
	}
	else if(0xFFFFFFFF == tmplate)
	{
		return true;
	}

	return false;
}

//0xA5 is the template A5 of select command response
//0x70 is the template 70 of read record cpmmand response
//0x77 is the template 77 of CCC command(COMPUTE CRYPTOGRAPHIC CHECKSUMMSD, only in MSD) and GAC command response
//0xBF is the template BF0C of template A5
//0x01 is the response of GET DATA command
//0x6F is the template 6F of template A5
//0x02 is the template 77 of GPO command

bool ParseAndStoreCardResponse(uint8_t *resp, int32_t resp_len, uint32_t tmplate, EMV_TLVOBJ *tlvs, int32_t tlvs_size)
{
	uint8_t command = 0x00;
	bool err_flg = false;
	EMV_TAG_ITEM item = {0};
	int32_t ret, i;

	eTRACE("paypass-info: start ParseAndStoreCardResponse");
	ret = emvtlv_decode(resp, resp_len, tlvs, tlvs_size, SINGLE_TLVOBJ);

	eTRACE("paypass-info: emvtlv_decode ret = %d", ret);
	if(ret < 0)
	{
		err_flg = true;
	}
	eTRACE("paypass-info: err_flg = %d", err_flg);
	if(err_flg)
	{
		return false;
	}
	else
	{
		for(i = 1; i < tlvs[0].childnum+1; i++)
		{
			ret = emv_taglib_ReadItemWithExactMatch(tlvs[i].tagname, EMVTAGTYPE_PAYPASS, &item);
			eTRACE("paypass-info: emv_taglib_ReadItemWithExactMatch ret = %d", ret);

			if(EMVTAGUPDATECONDITION_RA & item.Update)
			{
				eTRACE("paypass-info: flag35");
				if(IsKnown(tlvs[i].tagname))
				{
					eTRACE("paypass-info: flag36");
					if((IsNotPresent(tlvs[i].tagname) || IsEmpty(tlvs[i].tagname)) && \
					   (tlvs[i].valuelen >= item.minLen && tlvs[i].valuelen <= item.maxLen) && \
					   IsTagIncludeTemplateValid(tlvs[i].tagname, tmplate, command))
					{
						eTRACE("paypass-info: flag37");
						appdata_save(tlvs[i].tagname, tlvs[i].pvalue, tlvs[i].valuelen, OVERRIDED);
						eTRACE("paypass-info: flag38");
					}
					else
					{
						return false;
					}
				}
				else
				{
					eTRACE("paypass-info: flag39");
					if(IsEmpty(tlvs[i].tagname))
					{
						appdata_save(tlvs[i].tagname, tlvs[i].pvalue, tlvs[i].valuelen, OVERRIDED);
					}
					else
					{
						return false;
					}
				}
			}
		}

		return true;
	}
}
