int32_t GetTagFromList(uint32_t List, uint32_t *item_arry, int32_t size)
{
	uint8_t *list_ptr, *tmpbuf;
	int32_t len,i,tag_len,counter=0;

	if(item_arry == NULL || size < 0)
	{
		return 0;
	}

	list_ptr = appdata_find(List, &len);
	if(!list_ptr)
	{
		return 0;
	}

	while (i < len)
	{
		if(counter >= size)
		{
			break;
		}

		if((list_ptr[i] & 0x1F) == 0x1F)
		{
			if((list_ptr[i+1] & 0x80) == 0x80)
			{
				tag_len = 3;
			}
			else
			{
				tag_len = 2;
			}
		}
		else
		{
			tag_len = 1;
		}
		item_arry[counter++] = emv_hex2dec(list_ptr+i, tag_len);
		i += tag_len;
	}

	return counter;
}

uint8_t *GetAndRemoveFromList(uint32_t *itemLen, uint32_t List)
{
	uint8_t *list_ptr, *tmpbuf,*rest_buf;
	int32_t len,i,j,tag_len,list_len,len_byte,num_bytes;
	uint32_t sup_tags[] = {
	TAG_9F70_PROTECTED_DATA_ENVELOPE1,
	TAG_9F71_PROTECTED_DATA_ENVELOPE2,
	TAG_9F72_PROTECTED_DATA_ENVELOPE3,
	TAG_9F73_PROTECTED_DATA_ENVELOPE4,
	TAG_9F74_PROTECTED_DATA_ENVELOPE5,
	TAG_9F75_UNPROTECTED_DATA_ENVELOPE1,
	TAG_9F76_UNPROTECTED_DATA_ENVELOPE2,
	TAG_9F77_UNPROTECTED_DATA_ENVELOPE3,
	TAG_9F78_UNPROTECTED_DATA_ENVELOPE4,
	TAG_9F79_UNPROTECTED_DATA_ENVELOPE5,
	};
	uint32_t active_tag;
	bool sup_flag=false;

	list_ptr = appdata_find(List, &list_len);
	if(list_ptr == NULL && list_len == 0)
	{
		*itemLen = 0;
		return NULL;
	}

	i = 0;
	if(list_len > 1)
	{
		if(list_ptr[i] & 0x7F)
		{
			tag_len = 2;
		}
		else
		{
			tag_len = 1;
		}
	}
	else if(list_len == 1)
	{
		tag_len = 1;
	}
	else
	{
		tag_len = 0;
		*itemLen = 0;
		return NULL;
	}

	active_tag = emv_hex2dec(list_ptr, tag_len);
	for(j = 0; j < sizeof(sup_tags)/sizeof(uint32_t); j++)
	{
		if(active_tag == sup_tags[j])
		{
			sup_flag = true;
			break;
		}
	}

	if(!sup_flag)
	{
		*itemLen = 0;
		return NULL;
	}

	i += tag_len;

	if((list_ptr[i] & 0x80) == 0x00)
	{
		len_byte = 1;
		len = list_ptr[i];
		i++;
	}
	else
	{
		num_bytes = list_ptr[i] & 0x7F;  // 获取长度字节数
		len_byte = 1 + num_bytes;

		if (i + len_byte > list_len)
		{
			*itemLen = 0;
			return NULL;
		}

		len = 0;
		i++;

		for (j = 0; j < num_bytes; j++)
		{
			len = (len << 8) | list_ptr[i++];
		}

		// 检查长度是否合理（可选）
		if (len < 0 || len > 2048)
		{
			*itemLen = 0;
			return NULL;
		}
	}

	i += len;

	eTRACE("paypass-info: len = %d", len);
	eTRACE("paypass-info: i = %d", i);

	if(i > list_len)
	{
		*itemLen = 0;
		return NULL;
	}

	*itemLen = i;

	//warning, this API use malloc to get memory,must be free by caller
	tmpbuf = (uint8_t *)malloc(i);
	emv_memset(tmpbuf, 0, i);
	emv_memcpy(tmpbuf, list_ptr, i);

	if(list_len > i)
	{
		rest_buf = (uint8_t *)malloc(list_len - i);
		emv_memset(rest_buf, 0, list_len - i);
		emv_memcpy(rest_buf, list_ptr+i, list_len - i);
		appdata_save(List, rest_buf, list_len - i, OVERRIDED);
	}
	else
	{
		appdata_save(List, NULL, 0, OVERRIDED);
	}

	return tmpbuf;
}

